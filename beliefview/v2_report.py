from .experiment import SCEN_INDEX, SCENARIOS, build_config, load_records
from .v2 import (CORE_MODULES, FINAL_POLICIES, LOCK, PROTOCOL, REFERENCE_ARM, REPORT_MODULES, V2_DIR, load_frozen_v2,
                 source_checksum, verify_frozen_v2)
from .world import SPLITS


def _fmt_ci(d, k, digits=3):
    return f"{d[k]:+.{digits}f} [{d[k + '_lo']:+.{digits}f}, {d[k + '_hi']:+.{digits}f}]"


def tuning_rows(frozen):
    rows = []
    sel = frozen["tuning_log"]["selected_lam"]
    for lam, c in frozen["tuning_log"]["candidates"].items():
        rows.append(dict(lam=float(lam), n=c["n"], n_found=c["n_found"], found_by_deadline=c["found_by_deadline"],
                         found_A=c["A_matched"]["found_by_deadline"], found_B=c["B_motion_mismatch"]["found_by_deadline"],
                         mean_distance=c["mean_distance"], rmst=c["rmst"],
                         within_tolerance=float(lam) in frozen["tuning_log"]["eligible"], selected=float(lam) == sel))
    return rows


def build_report(v2_dir=V2_DIR, frozen=None, split=None, with_demo=True):
    """Everything here is computed from the saved records. The only episodes replayed are the two
    illustrative animation episodes (deterministic replays, checked against their records)."""
    from .cli import PAIRING_NOTE, make_animations, write_results_md
    from .plots import comparison_figure, exit_sweep_figure, map_figure
    frozen = frozen or load_frozen_v2()
    cfg = build_config(frozen["chosen"])
    exp, T, lam = cfg.experiment, cfg.experiment.deadline, cfg.planner.lam
    fp = PROTOCOL["final"]
    split = split or fp["split"]
    recs = load_records(v2_dir / "final_records.jsonl")
    srecs = load_records(v2_dir / "exit_sweep_records.jsonl")
    names = fp["scenarios"]
    n = len({r["idx"] for r in recs})
    # integrity of what was run: right split, complete, and the shared-lambda design in the records themselves
    assert all(r["split"] == split for r in recs + srecs)
    assert len(recs) == len(names) * n * len(FINAL_POLICIES)
    for r in recs:
        want = {"belief": lam, "belief_noneg": lam, REFERENCE_ARM: 0.0}.get(r["policy"])
        assert r["planner_lam"] == want, (r["policy"], r["planner_lam"])
    sweep = {h: [r for r in srecs if r["assumed_exit"] == h] for h in exp.exit_sweep}

    rows, diffs, curves = summarize(recs, T, exp.bootstrap)
    bsplit = behavior_split(recs)
    swrows = exit_sweep(sweep, T, exp.bootstrap)
    trows = tuning_rows(frozen)
    ref = [d for d in diffs if d["baseline"] == REFERENCE_ARM]
    write_csv(rows, v2_dir / "summary_by_scenario.csv")
    write_csv(diffs, v2_dir / "paired_differences.csv")
    write_csv(ref, v2_dir / "lambda_reference_arm.csv")
    write_csv(bsplit, v2_dir / "behavior_split.csv")
    write_csv(swrows, v2_dir / "exit_rate_sensitivity.csv")
    write_csv(trows, v2_dir / "validation_tuning.csv")
    np.savez(v2_dir / "curves.npz", **{f"{s}|{p}": v for (s, p), v in curves.items()})

    comparison_figure(rows, diffs, curves, T, names, v2_dir / "comparison.png", n_note=f"N={n} per scenario.",
                      title=f"BeliefView v2 - synthetic 2D simulation, fresh final episodes (split id {SPLITS[split]}), "
                            f"same subject trajectories for every policy; lam = {lam:g}. ")
    exit_sweep_figure(swrows, v2_dir / "exit_rate_sensitivity.png",
                      SCENARIOS[SCEN_INDEX["D_exit_mismatch"]].truth_motion.edge_exit_rate)
    map_figure(cfg.map, v2_dir / "map.png")
    meta = []
    # every frame is a keyframe so the local demo can seek and single-step exactly
    anims = make_animations(recs, cfg, res=v2_dir, split=split, ep_word="v2 final", extra_args=["-g", "1"], meta=meta)
    (v2_dir / "animation_meta.json").write_text(json.dumps(
        {"note": "Illustrative episodes selected by outcome (representative = scenario A BeliefView success with the "
                 "median detection time; failure = first scenario B BeliefView timeout whose subject was still inside). "
                 "Per-frame numbers are from the deterministic replay used to render the video.",
         "episodes": meta}, indent=1) + "\n")

    by = {(r["scenario"], r["policy"]): r for r in rows}
    head = [
        "# v2 results (headline; auto-generated by `python -m beliefview.cli v2-final` / `v2-report`)\n",
        f"Synthetic 2D simulation. N = {n} fresh final episodes per scenario (split id {SPLITS[split]}, run once), paired "
        f"across policies. Deadline T = {T} steps. Travel penalty lam = {lam:g}, selected on validation split id "
        f"{SPLITS[PROTOCOL['tuning']['split']]} by a rule fixed before any v2 episode existed. Config hash "
        f"`{frozen['config_hash']}`, protocol hash `{frozen['protocol_hash']}`, core source checksum "
        f"`{frozen['core_source_checksum']}`. Intervals are 95% percentile bootstrap over episodes "
        f"(B={exp.bootstrap}) and are **not adjusted** for the number of comparisons.\n",
        "The earlier v1 record (lam = 0, config hash `222bce7e37097894`, 100 test episodes per scenario that were run "
        "twice) is kept unmodified in `results/` (top level) and `archive/v1/`. v1 and v2 use different episodes and "
        "their tables are not merged.\n"]
    tl = frozen["tuning_log"]
    after = [
        "\n## How lam was chosen (validation split only)\n",
        f"Rule: {PROTOCOL['tuning']['rule']}. {tl['n_per_scenario']} validation episodes in each of scenarios A and B "
        f"(split id {SPLITS[PROTOCOL['tuning']['split']]}), BeliefView only, the same episodes for every candidate. "
        f"Best fraction {tl['best_found_by_deadline']:.3f}; selected lam = {tl['selected_lam']:g}.\n",
        md_table(trows, [("lam", lambda r: f"{r['lam']:g}"),
                         ("reacquired, A+B", lambda r: f"{r['found_by_deadline']:.3f} ({r['n_found']} of {r['n']})"),
                         ("A", lambda r: f"{r['found_A']:.2f}"), ("B", lambda r: f"{r['found_B']:.2f}"),
                         ("mean travel", lambda r: f"{r['mean_distance']:.1f}"), ("RMST", lambda r: f"{r['rmst']:.1f}"),
                         ("within 0.03 of best", lambda r: "yes" if r["within_tolerance"] else "no"),
                         ("selected", lambda r: "**yes**" if r["selected"] else "")]),
        "\n## Effect of the positive travel penalty: BeliefView minus the lam = 0 reference arm\n",
        f"The reference arm is BeliefView with lam = 0 and every other setting identical, run on the same final episodes. "
        "It is a labelled paired reference only: it was not a tuning candidate and is not a headline result. Differences "
        f"are BeliefView (lam = {lam:g}) minus the reference arm: `d_found` < 0 means the penalty cost reacquisitions; "
        "`d_distance` < 0 means it saved travel (all episodes, flown until first detection or the deadline).\n",
        md_table(ref, [("scenario", "scenario"),
                       (f"BeliefView (lam = {lam:g}) reacquired", lambda r: f"{by[(r['scenario'], 'belief')]['found_by_deadline']:.3f}"),
                       ("lam = 0 reference reacquired", lambda r: f"{by[(r['scenario'], REFERENCE_ARM)]['found_by_deadline']:.3f}"),
                       ("d_found [95% CI]", lambda r: _fmt_ci(r, "d_found")),
                       ("d_rmst [95% CI]", lambda r: _fmt_ci(r, "d_rmst", 1)),
                       ("mean travel, BeliefView", lambda r: f"{by[(r['scenario'], 'belief')]['mean_distance']:.1f}"),
                       ("mean travel, reference", lambda r: f"{by[(r['scenario'], REFERENCE_ARM)]['mean_distance']:.1f}"),
                       ("d_distance [95% CI]", lambda r: _fmt_ci(r, "d_distance", 1)),
                       ("both found", "both_found"), ("only BeliefView", "belief_only_found"),
                       ("only reference", "baseline_only_found"), ("neither", "neither_found")])]
    write_results_md(rows, diffs, bsplit, swrows, cfg, n, anims, frozen, res=v2_dir, policies=FINAL_POLICIES,
                     head=head, after_primary=after, ep_word="v2 final")
    _write_log(v2_dir, cfg, frozen, n, rows, anims, split)
    if with_demo:
        from .demo import build_demo
        build_demo()
    return rows, diffs


def _write_log(v2_dir, cfg, frozen, n, rows, anims, split):
    import matplotlib
    lock = json.loads((v2_dir / "FINAL_RUN_LOCK.json").read_text()) if (v2_dir / "FINAL_RUN_LOCK.json").exists() else {}
    L = ["# v2 experiment log\n",
         f"- beliefview {__version__}; python {platform.python_version()}; numpy {np.__version__}; matplotlib {matplotlib.__version__}",
         f"- v2 frozen at {frozen['frozen_at']}: config hash `{frozen['config_hash']}`, protocol hash `{frozen['protocol_hash']}` "
         "(both verified before the final run)",
         f"- source: core (simulation/inference/protocol) checksum at freeze `{frozen['core_source_checksum']}`, at the final run "
         f"`{lock.get('core_source_checksum')}`, when this log was written `{source_checksum(CORE_MODULES)}`; git revision "
         f"at the final run: {lock.get('git_revision')}; report-code checksum when this log was written "
         f"`{source_checksum(REPORT_MODULES)}` (analysis, plots, animate, cli, v2_report, demo)",
         f"- chosen: `{json.dumps(frozen['chosen'])}`; lam selected on validation split id 3 "
         f"(grid {PROTOCOL['tuning']['lam_grid']}, rule: {PROTOCOL['tuning']['rule']}); orbit margin, scan yaw and tau_left "
         "are the v1 values, not re-tuned",
         "- BeliefView and its no-miss-update ablation share one planner setting (`planner`, including `lam`); every "
         "final record stores the `planner_lam` it ran with, and the report asserts belief == belief_noneg == selected, "
         f"{REFERENCE_ARM} == 0",
         f"- `{REFERENCE_ARM}`: lam = 0 reference arm on the same final episodes; labelled, not a tuning candidate, not a headline",
         "- paired across policies: episode (trajectory, start, last-seen), per-step detection uniforms and measurement "
         "noise; NOT paired: the observations themselves, which depend on each policy's viewpoint",
         f"- base seed {cfg.experiment.base_seed}; episode streams = SeedSequence([base, scenario_idx, split_id, idx]); "
         f"v2 split ids: v2_val=3 (tuning), v2_final=4 (final); v1 used 0, 1, 2",
         f"- final episodes per scenario: {n} (split `{split}`); scenarios: {PROTOCOL['final']['scenarios']}; deadline {cfg.experiment.deadline}",
         f"- final run started {lock.get('started_at')}, completed {lock.get('completed_at')}, episode wall time "
         f"{lock.get('episode_wall_seconds')}s; `results/v2/FINAL_RUN_LOCK.json` blocks a second inferential run",
         f"- exit-rate sweep assumed values: {list(cfg.experiment.exit_sweep)} (scenario D, BeliefView only)",
         f"- max |sum(belief)+outside - 1| over all final runs: {max(r['max_conservation_err'] for r in rows):.2e}",
         "- animations (illustrative, selected by outcome): " + "; ".join(f"{k}={Path(p).name} ({sc} ep {i})" for k, sc, i, b, w, p in anims),
         "- raw per-episode records: results/v2/final_records.jsonl, results/v2/exit_sweep_records.jsonl, "
         "results/v2/validation_records.jsonl",
         "- this log is rewritten by `v2-report`, which recomputes tables from the saved records and runs no new episodes "
         "other than the two deterministic animation replays"]
    (v2_dir / "experiment_log.md").write_text("\n".join(L) + "\n")


def cmd_report(args):
    frozen = load_frozen_v2()
    # Config and protocol must still match the freeze. The core source checksum is not enforced here
    # (reporting runs no inferential episode); the freeze, final-run and current checksums are logged.
    verify_frozen_v2(frozen, check_source=False)
    if not (LOCK.exists() and json.loads(LOCK.read_text()).get("completed_at")):
        raise SystemExit("No completed v2 final run to report.")
    build_report(frozen=frozen)
    print(f"Rebuilt v2 report and demo from saved records in {V2_DIR}")


def cmd_demo(args):
    from .demo import build_demo
    print("Wrote", build_demo())
